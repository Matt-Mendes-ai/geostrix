// TASKS.csv #2610 — the tables of the bundled Exo 2 (latin, 400 and 600, from @fontsource/exo-2's WOFF files) that lib/svgFontEmbed.js
// subsets into the section / strip-log SVGs, written as src/lib/fonts/exo2Tables.js (base64 per table). Run once after @fontsource/exo-2
// changes: node scripts/fonts/build-exo2-tables.mjs
// Kept: the tables a TrueType font needs to render (OS/2 cmap glyf head hhea hmtx loca maxp name). Left out: GPOS / GSUB / GDEF / STAT
// (kerning and features: the embedded text is not kerned) and post (written as version 3 by the subsetter).
import fs from "node:fs";
import zlib from "node:zlib";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const KEEP = ["OS/2", "cmap", "glyf", "head", "hhea", "hmtx", "loca", "maxp", "name"];

function woffTables(file) {
  const b = fs.readFileSync(file);
  if (b.toString("latin1", 0, 4) !== "wOFF") throw new Error(`${file}: not a WOFF file`);
  const n = b.readUInt16BE(12), out = {};
  for (let i = 0; i < n; i++) {
    const o = 44 + i * 20, tag = b.toString("latin1", o, o + 4);
    const off = b.readUInt32BE(o + 4), comp = b.readUInt32BE(o + 8), orig = b.readUInt32BE(o + 12);
    const raw = b.subarray(off, off + comp);
    const data = comp < orig ? zlib.inflateSync(raw) : raw;
    if (data.length !== orig) throw new Error(`${file}: ${tag} is ${data.length} bytes, expected ${orig}`);
    if (KEEP.includes(tag)) out[tag] = Buffer.from(data).toString("base64");
  }
  for (const t of KEEP) if (!out[t]) throw new Error(`${file}: no ${t} table`);
  return out;
}

const dir = path.join(root, "node_modules/@fontsource/exo-2/files");
const fonts = { 400: woffTables(path.join(dir, "exo-2-latin-400-normal.woff")), 600: woffTables(path.join(dir, "exo-2-latin-600-normal.woff")) };
const ver = JSON.parse(fs.readFileSync(path.join(root, "node_modules/@fontsource/exo-2/package.json"), "utf8")).version;
const js = `// GENERATED by scripts/fonts/build-exo2-tables.mjs from @fontsource/exo-2 ${ver} (latin, 400 and 600) — do not edit.\n`
  + `// Exo 2 is licensed under the SIL Open Font License 1.1 (embedding a subset in a document is permitted). TASKS.csv #2610.\n`
  + `export const EXO2_TABLES = ${JSON.stringify(fonts)};\n`;
fs.mkdirSync(path.join(root, "src/lib/fonts"), { recursive: true });
fs.writeFileSync(path.join(root, "src/lib/fonts/exo2Tables.js"), js);
console.log("wrote src/lib/fonts/exo2Tables.js", js.length, "bytes");
